"""
Оценка поста по двум независимым измерениям + жёсткие фильтры.

Дайджест собирается в два слота, и у них РАЗНЫЕ критерии:

  • Слот «Экономика» — важные и понятные ВСЕМ новости про деньги: ключевая
    ставка, инфляция, курс рубля, цены, зарплаты, пенсии, налоги, ипотека,
    вклады. Здесь работает `econ_importance`.

  • Слот «Интересное» — ЯРКИЕ, вирусные новости для широкой аудитории канала:
    технологии, блокировки, утечки, мошенники, громкие события, неожиданные
    цифры. Здесь работает `brightness`. Важно: финансовый жаргон тут НЕ плюс —
    сухая аналитика («реструктуризация суверенного долга», «дивергенция
    политик центробанков») для обычного читателя скучна и получает штраф.

Жёсткие фильтры (для обоих слотов):
  • мат и военная/украинская повестка — пост исключается полностью;
  • реклама/интеграции — на дно;
  • шоу-бизнес/инфошум — сильный штраф.

Никаких внешних API: только регулярки, работают мгновенно. Модуль никогда не
бросает исключений — при любой ошибке вернёт нейтральную оценку.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

# ---------------------------------------------------------------------------
# Жёсткий бан: пост не попадает в сводку ни при каких условиях.
# ---------------------------------------------------------------------------
_BLOCK_RES = [
    # Нецензурная лексика (корни, с учётом словоформ).
    re.compile(
        r"\b(?:ху[йяеёи][а-яё]*|пизд[а-яё]*|[её]б[ао]н[а-яё]*|еб[аул][а-яё]*|"
        r"бля[дт]?[а-яё]*|\bбля\b|мудак[а-яё]*|мудач[а-яё]*|залуп[а-яё]*|"
        r"долбо[её]б[а-яё]*|пидор[а-яё]*|охуе[а-яё]*|нахуй|похуй)",
        re.IGNORECASE,
    ),
    # Война / украинская повестка.
    re.compile(
        r"\b(?:украин[а-яё]*|всу\b|зеленск[а-яё]*|\bсво\b|спецоперац[а-яё]*|"
        r"фронт[ае]?\b|обстрел[а-яё]*|ракетн[а-яё]* удар|наступлени[а-яё]*|"
        r"мобилизаци[а-яё]*|днр\b|лнр\b|донбасс[а-яё]*|херсон[а-яё]*|"
        r"авдеевк[а-яё]*|бахмут[а-яё]*|окоп[а-яё]*|миномет[а-яё]*|"
        r"военкор[а-яё]*|перемири[а-яё]*|боев(?:ых|ые) действ[а-яё]*)",
        re.IGNORECASE,
    ),
]

# ---------------------------------------------------------------------------
# Мягкий штраф: инфошум, который каналу не к лицу.
# ---------------------------------------------------------------------------
_NOISE_RE = re.compile(
    r"\b(?:актер[а-яё]*|актёр[а-яё]*|актрис[а-яё]*|певец|певц[а-яё]*|певиц[а-яё]*|"
    r"знаменитост[а-яё]*|шоу-?бизнес[а-яё]*|светск[а-яё]*|развод[ия]тся|"
    r"свадьб[а-яё]*|беременн[а-яё]*|инстаграм[а-яё]*|"
    r"киркоров[а-яё]*|пугачев[а-яё]*|пугачёв[а-яё]*|бузов[а-яё]*|собчак[а-яё]*|"
    r"сериал[а-яё]*|премьер[ае] фильм[а-яё]*|клип[а-яё]*|певч[а-яё]*|"
    r"гороскоп[а-яё]*|гадалк[а-яё]*|экстрасенс[а-яё]*|лотере[а-яё]*|"
    r"тикток[а-яё]*|реалити-?шоу)",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# Реклама/интеграции — мусор для новостной сводки.
# ---------------------------------------------------------------------------
_AD_RE = re.compile(
    r"(?:\berid\b|#реклама|на правах рекламы|промокод[а-яё]*|"
    r"скидк[а-яё]+ (?:до|по промо)|бесплатн[а-яё]+ вебинар[а-яё]*|"
    r"доходность до \d|инвестиции от [$€£]?\s?\d|"
    r"переходи(?:те)? по ссылке|жми на ссылку|регистрируйся|записывайся|"
    r"подписывайся на канал|забирай (?:гайд|чек-?лист|бонус)|"
    r"только сегодня|осталось \d+ мест|курс по (?:трейдингу|крипте|инвестициям))",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# ЭКОНОМИКА, ПОНЯТНАЯ ВСЕМ: то, что напрямую касается кошелька россиянина.
# ---------------------------------------------------------------------------
# Только то, что обычный человек ощущает кошельком. Голые названия валют
# (рубль/доллар/евро) сюда НЕ входят — они есть и в сухой иностранной аналитике;
# для слота «Экономика» важна именно бытовая тема (курс/цены/подорожание).
_EVERYDAY_RE = re.compile(
    r"\b(?:ключев[а-яё]+ ставк[а-яё]*|ставк[аиуео][а-яё]*|инфляци[а-яё]*|"
    r"подорожа[а-яё]*|подешевел[а-яё]*|дешевеет|дорожает|цен[аыуео][а-яё]*|"
    r"курс[а-яё]* (?:валют|рубл|доллар|евро|юан)|"
    r"бензин[а-яё]*|топлив[а-яё]*|солярк[а-яё]*|тариф[а-яё]*|жкх\b|коммунал[а-яё]*|"
    r"электричеств[а-яё]*|отоплени[а-яё]*|зарплат[а-яё]*|оклад[а-яё]*|"
    r"пенси[а-яё]*|пенсионер[а-яё]*|пособи[а-яё]*|выплат[а-яё]*|мрот\b|"
    r"прожиточн[а-яё]*|налог[а-яё]*|ндфл\b|вычет[а-яё]*|ипотек[а-яё]*|"
    r"кредит[а-яё]*|рассрочк[а-яё]*|вклад[а-яё]*|депозит[а-яё]*|"
    r"маткапитал[а-яё]*|материнск[а-яё]+ капитал[а-яё]*|субсиди[а-яё]*|"
    r"льгот[а-яё]*|кэшбэк[а-яё]*|сбережени[а-яё]*|накоплени[а-яё]*)",
    re.IGNORECASE,
)

# Базовые финансово-банковские термины (ядро профиля).
_CORE_RE = re.compile(
    r"\b(?:банк[а-яё]*|цб\b|центробанк[а-яё]*|рубл[а-яё]*|доллар[а-яё]*|"
    r"валют[а-яё]*|инфляци[а-яё]*|кредит[а-яё]*|ипотек[а-яё]*|вклад[а-яё]*|"
    r"депозит[а-яё]*|налог[а-яё]*|бюджет[а-яё]*|инвест[а-яё]*|финанс[а-яё]*|"
    r"эконом[а-яё]*|минфин[а-яё]*|росстат[а-яё]*|мосбирж[а-яё]*|"
    r"набиуллин[а-яё]*|сбер[а-яё]*|втб\b|тинькофф?[а-яё]*|альфа-?банк[а-яё]*|"
    r"платеж[а-яё]*|платёж[а-яё]*|банкомат[а-яё]*|зарплат[а-яё]*|пенси[а-яё]*)",
    re.IGNORECASE,
)

# Смежные «деловые» темы.
_NEAR_RE = re.compile(
    r"\b(?:бизнес[а-яё]*|компани[а-яё]*|рынок|рынк[а-яё]*|ритейл[а-яё]*|"
    r"экспорт[а-яё]*|импорт[а-яё]*|санкци[а-яё]*|нефт[а-яё]*|газ[а-яё]*|"
    r"закон[а-яё]*|госдум[а-яё]*|правительств[а-яё]*|указ[а-яё]*|"
    r"недвижимост[а-яё]*|застройщик[а-яё]*|аренд[а-яё]*)",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# СУХАЯ/ТЕХНИЧЕСКАЯ ФИНАНСОВАЯ АНАЛИТИКА: важно для профи, скучно для всех.
# В слоте «Интересное» это сильный штраф (если рядом нет ярких маркеров).
# ---------------------------------------------------------------------------
_DRY_RE = re.compile(
    r"\b(?:суверенн[а-яё]*|реструктуризац[а-яё]*|дефолт[а-яё]*|облигац[а-яё]*|"
    r"еврооблигац[а-яё]*|эмитент[а-яё]*|ликвидност[а-яё]*|котировк[а-яё]*|"
    r"фьючерс[а-яё]*|дериватив[а-яё]*|волатильн[а-яё]*|спред[а-яё]*|"
    r"транш[а-яё]*|купон[а-яё]*|доходност[а-яё]*|индекс[а-яё]*|ввп\b|"
    r"валов[а-яё]+ внутренн[а-яё]*|сальдо|профицит[а-яё]*|"
    r"монетарн[а-яё]*|рефинансир[а-яё]*|своп[а-яё]*|базисн[а-яё]+ пункт[а-яё]*|"
    r"листинг[а-яё]*|капитализац[а-яё]*|мультипликатор[а-яё]*|ebitda|"
    r"консолидир[а-яё]*|аллокац[а-яё]*|портфел[а-яё]*|бенчмарк[а-яё]*|"
    r"дивергенц[а-яё]*|макропрогноз[а-яё]*|конъюнктур[а-яё]*|"
    r"fsb\b|фрс\b|регулятор[а-яё]* (?:опубликова|представи|концепци))",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# ГАЙДЫ/ЛИСТИКЛЫ/ПОДБОРКИ: это контент, а не новость. Длинный пост «15 промптов
# для Claude» легко набирает кучу ключевых слов и пролезает в новостную сводку —
# отсекаем. Срабатывает на «<число> способов/правил/промптов…» и явных словах.
# ---------------------------------------------------------------------------
_HOWTO_RE = re.compile(
    r"(?:\b\d{1,3}\s+(?:способ[а-яё]*|при[её]м[а-яё]*|промпт[а-яё]*|"
    r"лайфхак[а-яё]*|совет[а-яё]*|причин[а-яё]*|шаг[а-яё]*|трюк[а-яё]*|"
    r"фишк[а-яё]*|идей|инструмент[а-яё]*|правил[а-яё]+ (?:как|для|чтобы))"
    r"|\b(?:промпт[а-яё]*|гайд[а-яё]*|чек-?лист[а-яё]*|подборк[а-яё]*|"
    r"лайфхак[а-яё]*|шпаргалк[а-яё]*|туториал[а-яё]*|мануал[а-яё]*))",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# ЯРКОСТЬ: маркеры новостей, которые цепляют широкую аудиторию.
# ---------------------------------------------------------------------------
_BRIGHT_RE = re.compile(
    r"\b(?:gmail|google|гугл[а-яё]*|microsoft|майкрософт[а-яё]*|windows|"
    r"apple|эпл[а-яё]*|iphone|айфон[а-яё]*|android|андроид[а-яё]*|"
    r"телеграм[а-яё]*|whatsapp|ватсап[а-яё]*|youtube|ютуб[а-яё]*|"
    r"нейросет[а-яё]*|chatgpt|openai|anthropic|claude|"
    r"искусственн[а-яё]+ интеллект[а-яё]*|\bии\b|робот[а-яё]*|дрон[а-яё]*|"
    r"приложени[а-яё]*|мессенджер[а-яё]*|госуслуг[а-яё]*|биометри[а-яё]*|"
    r"дипфейк[а-яё]*|блокир[а-яё]*|заблок[а-яё]*|запрет[а-яё]*|запрещ[а-яё]*|"
    r"взлом[а-яё]*|утечк[а-яё]*|хакер[а-яё]*|мошенник[а-яё]*|мошеннич[а-яё]*|"
    r"скам[а-яё]*|кибер[а-яё]*|слежк[а-яё]*|прослуш[а-яё]*|штраф[а-яё]*|"
    r"арест[а-яё]*|обыск[а-яё]*|задержа[а-яё]*|уволен[а-яё]*|уволил[а-яё]*|"
    r"отставк[а-яё]*|банкрот[а-яё]*|скандал[а-яё]*|обанкрот[а-яё]*|"
    r"расследован[а-яё]*|сбой[а-яё]*|авари[а-яё]*|отключ[а-яё]*|отмен[а-яё]*|"
    r"впервые|рекорд[а-яё]*|обвал[а-яё]*|рухнул[а-яё]*|взлетел[а-яё]*|"
    r"подскочил[а-яё]*|историческ[а-яё]*|крупнейш[а-яё]*|неожида[а-яё]*|"
    r"сенсац[а-яё]*|миллиард[а-яё]*|триллион[а-яё]*|"
    r"маркетплейс[а-яё]*|озон\b|ozon|wildberries|вайлдберр[а-яё]*|"
    r"доставк[а-яё]*|такси\b|перелет[а-яё]*|авиабилет[а-яё]*|ржд\b|"
    r"отпуск[а-яё]*|загранпаспорт[а-яё]*|школ[а-яё]*|квартир[а-яё]*)",
    re.IGNORECASE,
)


@dataclass
class Analysis:
    blocked: bool          # мат/война — исключить полностью
    econ_importance: float # важность для слота «Экономика» (0 → не сюда)
    brightness: float      # яркость для слота «Интересное»
    tag: str               # короткая причина для логов


def analyze(text: str) -> Analysis:
    """Возвращает Analysis с двумя независимыми оценками + флагом блокировки."""
    if not text or not text.strip():
        return Analysis(False, 0.0, 0.3, "empty")
    try:
        low = text.lower()

        for blocked in _BLOCK_RES:
            if blocked.search(low):
                return Analysis(True, 0.0, 0.0, "blocked")

        if _AD_RE.search(low):
            return Analysis(False, 0.0, 0.05, "ad")

        noise = bool(_NOISE_RE.search(low))
        howto = bool(_HOWTO_RE.search(low))
        everyday = len(_EVERYDAY_RE.findall(low))
        core = len(_CORE_RE.findall(low))
        near = len(_NEAR_RE.findall(low))
        dry = len(_DRY_RE.findall(low))
        bright = len(_BRIGHT_RE.findall(low))

        # --- Экономическая важность (для всех) ---
        # Решает БЫТОВАЯ экономика; ядро/смежное лишь слегка добавляют, чтобы
        # одни только банковские термины не протащили в слот сухую новость.
        econ_importance = (
            min(everyday, 5) * 0.55
            + min(core, 5) * 0.12
            + min(near, 4) * 0.05
        )
        if dry:
            econ_importance *= 0.4   # сухая/иностранная аналитика — не «для всех»
        if noise:
            econ_importance *= 0.3
        if howto:
            econ_importance *= 0.1   # гайд/подборка — это не новость

        # --- Яркость (для широкой аудитории) ---
        brightness = 0.70 + min(bright, 5) * 0.22
        if dry and bright == 0:
            brightness *= 0.45          # чистая сухая аналитика — скучно
        elif dry > bright:
            brightness *= 0.70          # перевес жаргона над яркостью
        if noise:
            brightness *= 0.25          # шоу-бизнес — «яркость» не того сорта
        if howto:
            brightness *= 0.5           # подборка/гайд — не горячая новость

        tag = f"ev={everyday},core={core},dry={dry},br={bright}{',howto' if howto else ''}"
        return Analysis(False, econ_importance, brightness, tag)
    except Exception:  # noqa: BLE001
        return Analysis(False, 0.0, 0.7, "error")


# --- Совместимость: прежний интерфейс score_text → множитель релевантности. ---
def score_text(text: str) -> tuple[float, str]:
    a = analyze(text)
    if a.blocked:
        return 0.0, "blocked"
    return 1.0 + a.econ_importance, a.tag
