"""
Оценка релевантности поста для новостного канала банка (ОТП).

Логика трёхуровневая:
  1. Жёсткий бан — нецензурная лексика и военная/украинская повестка:
     пост исключается полностью (factor = 0).
  2. Мягкий штраф — шоу-бизнес, знаменитости, скандалы, лотереи и прочий
     инфошум: пост резко теряет вес, но теоретически может пройти,
     если он одновременно сильно экономический.
  3. Буст — экономика, банки, финансы, бизнес, технологии/рынки:
     чем больше профильных терминов, тем выше вес.

Никаких внешних API: словарные правила на регулярках, работают мгновенно.
Модуль никогда не бросает исключений — при любой ошибке вернёт нейтральный вес.
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 1. Жёсткий бан: пост не попадает в сводку ни при каких условиях.
# ---------------------------------------------------------------------------
_BLOCK_RES = [
    # Нецензурная лексика (корни, с учётом словоформ).
    re.compile(
        r"\b(?:ху[йяеёи][а-яё]*|пизд[а-яё]*|[её]б[ао]н[а-яё]*|еб[аул][а-яё]*|"
        r"бля[дт]?[а-яё]*|\bбля\b|мудак[а-яё]*|мудач[а-яё]*|залуп[а-яё]*|"
        r"долбо[её]б[а-яё]*|пидор[а-яё]*|охуе[а-яё]*|нахуй|похуй)",
        re.IGNORECASE,
    ),
    # Война / украинская повестка.
    re.compile(
        r"\b(?:украин[а-яё]*|всу\b|зеленск[а-яё]*|\bсво\b|спецоперац[а-яё]*|"
        r"фронт[ае]?\b|обстрел[а-яё]*|ракетн[а-яё]* удар|наступлени[а-яё]*|"
        r"мобилизаци[а-яё]*|днр\b|лнр\b|донбасс[а-яё]*|херсон[а-яё]*|"
        r"авдеевк[а-яё]*|бахмут[а-яё]*|окоп[а-яё]*|миномет[а-яё]*|"
        r"военкор[а-яё]*|перемири[а-яё]*|боев(?:ых|ые) действ[а-яё]*)",
        re.IGNORECASE,
    ),
]

# ---------------------------------------------------------------------------
# 2. Мягкий штраф: инфошум, который банковскому каналу не к лицу.
# ---------------------------------------------------------------------------
_NOISE_RE = re.compile(
    r"\b(?:актер[а-яё]*|актёр[а-яё]*|актрис[а-яё]*|певец|певц[а-яё]*|певиц[а-яё]*|"
    r"знаменитост[а-яё]*|шоу-?бизнес[а-яё]*|светск[а-яё]*|скандал[а-яё]*|"
    r"развод[ия]тся|свадьб[а-яё]*|беременн[а-яё]*|инстаграм[а-яё]*|"
    r"киркоров[а-яё]*|пугачев[а-яё]*|пугачёв[а-яё]*|бузов[а-яё]*|собчак[а-яё]*|"
    r"сериал[а-яё]*|премьер[ае] фильм[а-яё]*|клип[а-яё]*|певч[а-яё]*|"
    r"гороскоп[а-яё]*|гадалк[а-яё]*|экстрасенс[а-яё]*|лотере[а-яё]*|"
    r"тикток[а-яё]*|реалити-?шоу)",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# 2б. Реклама/интеграции: для новостной сводки банка это мусор.
# ---------------------------------------------------------------------------
_AD_RE = re.compile(
    r"(?:\berid\b|#реклама|на правах рекламы|промокод[а-яё]*|"
    r"скидк[а-яё]+ (?:до|по промо)|бесплатн[а-яё]+ вебинар[а-яё]*|"
    r"доходность до \d|инвестиции от [$€£]?\s?\d|"
    r"переходи(?:те)? по ссылке|жми на ссылку|регистрируйся|записывайся|"
    r"подписывайся на канал|забирай (?:гайд|чек-?лист|бонус)|"
    r"только сегодня|осталось \d+ мест|курс по (?:трейдингу|крипте|инвестициям))",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# 3. Буст: профильные темы. Вес 2 — ядро (банки/макро), вес 1 — около.
# ---------------------------------------------------------------------------
_CORE_RE = re.compile(
    r"\b(?:банк[а-яё]*|цб\b|центробанк[а-яё]*|ключев[а-яё]+ ставк[а-яё]*|"
    r"ставк[а-яё]*|рубл[а-яё]*|доллар[а-яё]*|евро\b|юан[а-яё]*|валют[а-яё]*|"
    r"инфляци[а-яё]*|кредит[а-яё]*|ипотек[а-яё]*|вклад[а-яё]*|депозит[а-яё]*|"
    r"налог[а-яё]*|бюджет[а-яё]*|акци[ийя][а-яё]*|облигаци[а-яё]*|бирж[а-яё]*|"
    r"инвест[а-яё]*|финанс[а-яё]*|эконом[а-яё]*|минфин[а-яё]*|росстат[а-яё]*|"
    r"мосбирж[а-яё]*|набиуллин[а-яё]*|сбер[а-яё]*|втб\b|тинькофф?[а-яё]*|"
    r"альфа-?банк[а-яё]*|карт[а-яё]* (?:мир|visa|mastercard)|платеж[а-яё]*|"
    r"платёж[а-яё]*|перевод[а-яё]* (?:денег|средств)|эквайринг[а-яё]*|"
    r"банкомат[а-яё]*|вкладчик[а-яё]*|заемщик[а-яё]*|заёмщик[а-яё]*|"
    r"антифрод[а-яё]*|мошеннич[а-яё]*|скам[а-яё]*|пенси[а-яё]*|зарплат[а-яё]*|"
    r"мрот\b|прожиточн[а-яё]+ минимум[а-яё]*)",
    re.IGNORECASE,
)

_NEAR_RE = re.compile(
    r"\b(?:бизнес[а-яё]*|компани[а-яё]*|рынок|рынк[а-яё]*|ритейл[а-яё]*|"
    r"маркетплейс[а-яё]*|озон\b|wildberries|вайлдберриз[а-яё]*|яндекс[а-яё]*|"
    r"авито\b|нефт[а-яё]*|газ[а-яё]*|экспорт[а-яё]*|импорт[а-яё]*|санкци[а-яё]*|"
    r"тариф[а-яё]*|цен[ыа] (?:на|выросл|упал)|подорожа[а-яё]*|подешевел[а-яё]*|"
    r"банкрот[а-яё]*|штраф[а-яё]*|регулятор[а-яё]*|закон[а-яё]*|госдум[а-яё]*|"
    r"правительств[а-яё]*|указ[а-яё]*|маркетинг[а-яё]*|реклам[а-яё]*|бренд[а-яё]*|"
    r"стартап[а-яё]*|ии\b|нейросет[а-яё]*|искусственн[а-яё]+ интеллект[а-яё]*|"
    r"технологи[а-яё]*|приложени[а-яё]*|сервис[а-яё]*|подписк[а-яё]*|"
    r"недвижимост[а-яё]*|застройщик[а-яё]*|аренд[а-яё]*|крипто[а-яё]*|"
    r"битко[ий]н[а-яё]*|майнинг[а-яё]*)",
    re.IGNORECASE,
)


def score_text(text: str) -> tuple[float, str]:
    """
    Возвращает (множитель_релевантности, причина).
      0.0  — пост запрещён (мат / военная повестка);
      <1.0 — нерелевантный инфошум;
      1.0  — нейтрально;
      >1.0 — профильная тема (экономика/банки/бизнес).
    """
    if not text or not text.strip():
        return 0.6, "no-text"
    try:
        lowered = text.lower()

        for blocked in _BLOCK_RES:
            if blocked.search(lowered):
                return 0.0, "blocked"

        core_hits = len(_CORE_RE.findall(lowered))
        near_hits = len(_NEAR_RE.findall(lowered))
        noise = bool(_NOISE_RE.search(lowered))
        is_ad = bool(_AD_RE.search(lowered))

        if is_ad:
            return 0.1, "ad"               # реклама/интеграция — на дно

        # Базовый вес темы: ядро двигает сильно, смежные темы — умеренно.
        topic = min(core_hits, 6) * 0.30 + min(near_hits, 6) * 0.12

        if noise and core_hits == 0:
            return 0.15, "noise"          # чистый шоу-бизнес — почти на дно
        if noise:
            topic *= 0.5                   # скандал с экономикой — сильный штраф

        if core_hits == 0 and near_hits == 0:
            return 0.45, "neutral"         # не по профилю — заметно ниже

        return 1.0 + topic, f"core={core_hits},near={near_hits}"
    except Exception:  # noqa: BLE001
        return 1.0, "error"
